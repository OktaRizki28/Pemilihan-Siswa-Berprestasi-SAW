    private void b_tampilActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_b_tampilActionPerformed
    try {

        String pilihan = c_laporan.getSelectedItem().toString();

        String file = "";

        switch (pilihan) {

            case "Data Siswa":
                file = "src/aplikasi_mainReport/Report_DataSiswa.jrxml";
                break;

            case "Kriteria":
                file = "src/aplikasi_mainReport/Report_Kriteria.jrxml";
                break;

            case "Sub Kriteria":
                file = "src/aplikasi_mainReport/Report_subKriteria.jrxml";
                break;

            case "Penilaian":
                file = "src/aplikasi_mainReport/Report_Penilaian.jrxml";
                break;

            case "Rangking":
                file = "src/aplikasi_mainReport/Report_Rangking.jrxml";
                break;
        }

        if(file.equals("")){
            JOptionPane.showMessageDialog(null,
                    "Silakan pilih jenis laporan.");
            return;
        }

        // Parameter Report
        HashMap<String, Object> parameter = new HashMap<>();

        SimpleDateFormat sdf = new SimpleDateFormat(
                "EEEE, dd MMMM yyyy",
                new Locale("id","ID"));

        parameter.put("tgl", "Bogor, " + sdf.format(new Date()));

        // Compile Report
        JasperReport report = JasperCompileManager.compileReport(file);

        // Isi Report
        jasperPrint = JasperFillManager.fillReport(report, parameter, conn);

        // Preview
        JRViewer viewer = new JRViewer(jasperPrint);

        pn_preview.removeAll();
        pn_preview.setLayout(new BorderLayout());
        pn_preview.add(viewer, BorderLayout.CENTER);
        pn_preview.revalidate();
        pn_preview.repaint();

    } catch (Exception e) {

        JOptionPane.showMessageDialog(null,
                e.toString());

    }

    }//GEN-LAST:event_b_tampilActionPerformed

