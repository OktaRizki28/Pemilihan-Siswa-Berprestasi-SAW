    private void tampilTanggalJam() {

        Locale indonesia = new Locale("id", "ID");

        Timer timer = new Timer(1000, e -> {

            Date sekarang = new Date();

            SimpleDateFormat formatTanggal =
                    new SimpleDateFormat("EEEE, dd MMMM yyyy", indonesia);

            SimpleDateFormat formatJam =
                    new SimpleDateFormat("HH:mm:ss");

            tanggal.setText(formatTanggal.format(sekarang));
            jam.setText(formatJam.format(sekarang));

        });

        timer.start();
}


